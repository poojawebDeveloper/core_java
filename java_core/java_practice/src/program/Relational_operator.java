package program;

public class Relational_operator {

	public static void main(String[] args) {
     int num=60;
     int num1=80;
     
     System.out.println(num==num1);//false
     System.out.println(num!=num1);//true
     System.out.println(num>num1);//false
     System.out.println(num<num1);//true
     System.out.println(num>=num1);//false
     System.out.println(num<=num1);//true
	}

}
