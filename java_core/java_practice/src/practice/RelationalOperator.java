package practice;

public class RelationalOperator {

	public static void main(String[] args) {
		int num= 60;
		int num1=40;
		
		System.out.println(num==num1);//false
		System.out.println(num!=num1);//true
		System.out.println(num>num1);//true
		System.out.println(num1<num);//true
		System.out.println(num<num1);//false
		
	}

}
