package practice;

public class PositiveNegative {

	public static void main(String[] args) {
     int num=-56;
     
     if(num==0)
     {
    	System.out.println("zero");
     }
     else if(num>0)
     {
    	 System.out.println("positive");
     }
     else if(num<0)
     {
    	 System.out.println("Negative");
     }
     else
     {
    	 System.out.println("invalid number");
     }
	}

}
