package practice;

public class RelationOperator {

	public static void main(String[] args) {
		int num=20;
		int num1=30;
		System.out.println(num==num1);//false
		System.out.println(num!=num1);//true
		System.out.println(num>num1);//false
		System.out.println(num<num1);//true
		System.out.println(num>=num1);//false
		System.out.println(num<=num1);//true
		
		System.out.println("---------------------------------------");
		
		int a=90;
		int b=80;
		System.out.println(a==b);//false
		System.out.println(a!=b);//true
		System.out.println(a>b);//true
		System.out.println(a<b);//false
		System.out.println(a>=b);//true
		System.out.println(a<=b);//false
		
	}

}
